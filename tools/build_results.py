#!/usr/bin/env python3
"""Generate scenario result pages from the manifests, the Lean sources and the recorded evidence (stdlib only).

    python3 tools/build_results.py           # (re)write generated files
    python3 tools/build_results.py --check   # exit 1 if any generated file is out of date (no writes)

For every scenarios/SC-XX/ it generates:
  result.md        status line; the manifest's Lean theorems with one-line readings taken from the theorem docstrings
                   (`/-- ... -/` immediately before the declaration); necessity witnesses; runtime evidence with the
                   preregistration id, overall verdict and per-hypothesis outcome read from the evidence JSON; premises
                   grouped by evidence status; what does NOT hold; the done-criteria table of RUNTIME-VM-HANDOFF.md §10
                   computed from manifest fields. Criterion 5 (independent human review) is always OPEN, and no
                   criterion is ever reported as met: the vocabulary is OPEN / ASSUMED / PARTIAL / RECORDED / REFUTED.
  tests/README.md  exact commands for the claim check, Lean modules, harness tests, runners and evidence rechecks,
                   listed only for files that exist.
  threat.md        ONLY if it still says "catalog draft" (or was generated before): regenerated from the manifest.

A file containing the marker `<!-- hand-written -->` is never touched. Generated files carry GEN_MARKER. In a generated
result.md, a block `<!-- notes:begin --> ... <!-- notes:end -->` is preserved verbatim (hand-written caveats that the
manifest does not record).
Nothing here re-runs Lean or any experiment: every status shown is recorded metadata.
"""
import argparse
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCEN = ROOT / "scenarios"
GEN_MARKER = "<!-- generated by tools/build_results.py from manifest.json, Lean sources and evidence files; edit those, not this file -->"
HAND_MARKER = "<!-- hand-written -->"
NOTES_RE = re.compile(r"<!-- notes:begin -->.*?<!-- notes:end -->", re.S)
WITNESS_RE = re.compile(r"(_breaks$|_breaks_|nogo|no_go|without|survives|^forged|_exceeds$|_leaks$|fools|"
                        r"counterexample|unbounded)")
DECL_RE = re.compile(r"(?:/--(?P<doc>(?:(?!-/).)*?)-/\s*)?(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|noncomputable)\s+)*"
                     r"^(?P<kind>theorem|lemma)\s+(?P<name>[\w.']+)", re.S | re.M)
HYP_RE = re.compile(r"^(?:#{2,4}\s+|\*\*|- \*\*)(?P<label>[HUDR]\d+)\b[\s:.(—-]*(?P<title>[^\n]*)", re.M)
EVIDENCE_ORDER = ("OBSERVED_FAILURE", "RUNTIME_VALIDATED", "TESTED_NOT_PROVED", "NOT_RUN", "NOT_APPLICABLE")


# ---------------------------------------------------------------- sources

def lean_decls(path, cache={}):
    """name -> one-line docstring (or None) for every theorem/lemma in a Lean file"""
    if path in cache:
        return cache[path]
    out = {}
    p = ROOT / path
    if p.is_file():
        for m in DECL_RE.finditer(p.read_text(encoding="utf-8")):
            out.setdefault(m.group("name"), one_liner(m.group("doc")))
    cache[path] = out
    return out


def one_liner(doc):
    if not doc:
        return None
    t = " ".join(doc.replace("**", "").split())
    t = re.sub(r"^\(?[0-9]+[a-z]?[.)]\s+", "", t)  # a leading enumeration such as "1." or "2b."
    ends = [m.start() for m in re.finditer(r"(?<=[.!?])\s+(?=[A-Z(`])", t)]
    for e in ends:  # first sentence, unless it is too short to say anything
        if e >= 25:
            t = t[:e]
            break
    return t if len(t) <= 240 else t[:237].rstrip() + "..."


def find_decl(name, path):
    decls = lean_decls(path)
    parts = name.split(".")
    for i in range(len(parts)):
        cand = ".".join(parts[i:])
        if cand in decls:
            return cand, decls[cand]
    return parts[-1], None


def prereg_index(cache={}):
    """prereg id -> path, and sha256 -> id"""
    if cache:
        return cache["by_id"], cache["by_sha"]
    by_id, by_sha = {}, {}
    for f in sorted((ROOT / "prereg").glob("*.md")):
        text = f.read_text(encoding="utf-8")
        m = re.search(r"\*\*ID:\*\*\s*`([^`]+)`", text)
        if m:
            by_id.setdefault(m.group(1), f)
            by_sha[hashlib.sha256(f.read_bytes()).hexdigest()] = m.group(1)
    cache.update(by_id=by_id, by_sha=by_sha)
    return by_id, by_sha


def hyp_titles(prereg_path):
    titles = {}
    if prereg_path and prereg_path.is_file():
        for m in HYP_RE.finditer(prereg_path.read_text(encoding="utf-8")):
            t = re.sub(r"\s*\(`.*$", "", m.group("title"))
            t = t.split("**")[0].strip().strip("().:").strip()
            titles.setdefault(m.group("label"), t[:90])
    return titles


def summarise_json(path):
    """(prereg id, overall, [(label, verdict, detail)]) from a recorded evidence JSON, or None"""
    p = ROOT / path
    try:
        d = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(d, dict):
        return None
    by_id, by_sha = prereg_index()
    pid = d.get("prereg_id") or d.get("prereg") or by_sha.get(d.get("prereg_sha256") or "")
    overall = d.get("overall") or d.get("verdict") or d.get("status")
    rows = []
    if isinstance(d.get("per_hypothesis"), dict):
        for k, v in d["per_hypothesis"].items():
            det = "{}/{} repetitions passed".format(v.get("passed"), v.get("reps") or v.get("ran"))
            if v.get("negative_control"):
                det += " (negative control: the weakened configuration was caught)"
            rows.append((k, v.get("verdict"), det))
    elif isinstance(d.get("phases"), dict):
        for k, v in d["phases"].items():
            if not isinstance(v, dict):
                continue
            det = []
            if "success" in v and "n" in v:
                det.append("{}/{} succeeded".format(v["success"], v["n"]))
            if v.get("check_trace"):
                det.append("check_trace " + str(v["check_trace"]))
            if isinstance(v.get("attacks"), list):
                det.append("{} attacks".format(len(v["attacks"])))
            if isinstance(v.get("controls"), (list, dict)):
                det.append("{} controls".format(len(v["controls"])))
            rows.append((k, v.get("verdict", "reported"), "; ".join(det)))
    else:
        for k, v in d.items():
            if re.fullmatch(r"[A-Z]\d+", k) and isinstance(v, dict):
                det = "; ".join(str(x) for x in (v.get("observed"), v.get("rule")) if x)
                rows.append((k, v.get("verdict", "reported"), det))
    return pid, overall, rows


# ---------------------------------------------------------------- rendering

def path_refs(manifests):
    c = Counter()
    for m in manifests:
        for p in {t["path"] for t in m["theorems"]}:
            c[p] += 1
    return c


def render_result(m, refs, notes=None):
    sid = m["id"]
    thms = m["theorems"]
    data_ev = [e for e in m["evidence"] if e["path"].endswith(".json")]
    summaries = {e["path"]: summarise_json(e["path"]) for e in data_ev}
    preregs = sorted({s[0] for s in summaries.values() if s and s[0]})
    witnesses_listed = [t for t in thms if WITNESS_RE.search(t["name"].split(".")[-1])]
    L = ["# {}: result".format(sid), "", GEN_MARKER, ""]
    ev_line = ("preregistered reference run(s) " + ", ".join("`{}`".format(p) for p in preregs)) if preregs else (
        "recorded files listed below" if m["evidence"] else "none (Lean model only)")
    L += ["**{}.** {}".format(m["status"], m["title"]), "",
          "This page is generated from `manifest.json`. It is recorded metadata, **not deployment assurance**.",
          "- Lean results: {} theorem reference(s), {} of them necessity witnesses.".format(len(thms), len(witnesses_listed)),
          "- Runtime evidence: {}.".format(ev_line),
          "- Runtime evidence, where present, is from reference runs on a single host; nothing ran on production "
          "infrastructure.",
          "- Independent human review: **not recorded** (done-criterion 5 is OPEN).", ""]
    if notes:
        L += ["## Hand-written notes (preserved verbatim)", "", notes, ""]
    L += ["## Bad event", "", m["bad_event"], ""]
    # theorems
    L += ["## Lean results", "", "Readings are the first sentence of each theorem's docstring. The statement itself is "
          "authoritative; see the file.", "", "| theorem | file | reading |", "|---|---|---|"]
    for t in thms:
        if t in witnesses_listed:
            continue
        name, doc = find_decl(t["name"], t["path"])
        L.append("| `{}` | `{}` | {} |".format(name, t["path"], (doc or "(no docstring)").replace("|", "/")))
    L += ["", "### Necessity witnesses", ""]
    rows = [(find_decl(t["name"], t["path"]), t["path"]) for t in witnesses_listed]
    own = [p for p in sorted({t["path"] for t in thms}) if refs[p] == 1]
    listed = {r[0][0] for r in rows}
    for p in own:
        for name, doc in lean_decls(p).items():
            if WITNESS_RE.search(name.split(".")[-1]) and name not in listed:
                rows.append(((name, doc), p))
                listed.add(name)
    if rows:
        L += ["Each witness exhibits a concrete trace showing that a check or premise cannot be dropped.", "",
              "| witness | file | reading |", "|---|---|---|"]
        L += ["| `{}` | `{}` | {} |".format(n, p, (d or "(no docstring)").replace("|", "/")) for (n, d), p in rows]
    else:
        L.append("None recorded.")
    # evidence
    L += ["", "## Runtime evidence", ""]
    if not m["evidence"]:
        L.append("None. The scenario is supported by its Lean model only.")
    by_id, _ = prereg_index()
    for e in m["evidence"]:
        exists = (ROOT / e["path"]).exists()
        L.append("- `{}` — recorded outcome **{}**{}. {}".format(
            e["path"], e.get("outcome", "?"), "" if exists else " (FILE MISSING)", e.get("purpose", "")))
        s = summaries.get(e["path"])
        if s and s[2]:
            titles = hyp_titles(by_id.get(s[0])) if s[0] else {}
            L += ["", "  Preregistration: `{}`; overall verdict in the file: **{}**.".format(s[0] or "not recorded",
                                                                                           s[1]), "",
                  "  | item | prereg title | verdict | detail |", "  |---|---|---|---|"]
            for lab, ver, det in s[2]:
                L.append("  | {} | {} | {} | {} |".format(lab, titles.get(lab, ""), ver, det.replace("|", "/")))
            L.append("")
    # premises
    L += ["", "## Premises (from the manifest)", ""]
    groups = {}
    for a in m["assumptions"]:
        groups.setdefault(a["evidence"], []).append(a)
    for ev in sorted(groups, key=lambda x: EVIDENCE_ORDER.index(x) if x in EVIDENCE_ORDER else 99):
        L += ["**Evidence {}:**".format(ev), ""]
        for a in groups[ev]:
            L.append("- `{}`: {} (proof: {}; applicability: {}; usefulness: {})".format(
                a["id"], a["text"], a["proof"], a["applicability"], a["usefulness"]))
        L.append("")
    # what does NOT hold
    L += ["## What does NOT hold", "", "- This is not deployment assurance, and no claim extends beyond the scope "
          "below.", "- Scope (manifest): " + m["scope"]]
    for a in m["assumptions"]:
        if a["applicability"] != "ESTABLISHED":
            L.append("- Not established as applying to a real deployment: {} (`{}`; applicability {}).".format(
                a["text"].rstrip("."), a["id"], a["applicability"]))
    for k, v in m.get("scope_axes", {}).items():
        if v.get("status") != "NOT_APPLICABLE":
            L.append("- Scope axis `{}` is {}: {}".format(k, v.get("status"), v.get("note", "")))
    # done criteria
    L += ["", "## Done-criteria (RUNTIME-VM-HANDOFF.md §10), computed from the manifest", "",
          "| # | criterion | status | basis |", "|---|---|---|---|"]
    L += ["| {} | {} | {} | {} |".format(i, c, s, b) for i, (c, s, b) in enumerate(done_criteria(m, summaries), 1)]
    L += ["", "Statuses never read MET: the strongest is RECORDED (a preregistered single-host run recorded a pass).",
          "Criterion 5 is OPEN by construction until an independent human review is recorded.", ""]
    return "\n".join(L)


def done_criteria(m, summaries):
    axes = {k: v.get("status") for k, v in m.get("scope_axes", {}).items()}
    pre_pass = [s for s in summaries.values() if s and s[0] and str(s[1]).upper() == "PASS"]
    any_fail = any(e.get("outcome") == "FAIL" for e in m["evidence"])
    use = [a for a in m["assumptions"] if "usefulness" in a["id"]]
    if any(a["usefulness"] == "OBSERVED_FAILURE" for a in m["assumptions"]):
        c1 = ("REFUTED", "a recorded usefulness failure")
    elif any(a["evidence"] == "TESTED_NOT_PROVED" for a in use) and pre_pass:
        c1 = ("RECORDED", "premise `{}` has evidence TESTED_NOT_PROVED and a preregistered single-host run passed"
              .format(next(a["id"] for a in use if a["evidence"] == "TESTED_NOT_PROVED")))
    else:
        c1 = ("OPEN", "no recorded honest-task run")
    if pre_pass:
        c2 = ("RECORDED", "preregistered negative controls and attacks passed (single host)" +
              ("; a FAIL is also recorded" if any_fail else ""))
    else:
        c2 = ("OPEN", "no preregistered negative-control run" + ("; a FAIL is recorded" if any_fail else ""))
    if any("Refinement" in t["path"] for t in m["theorems"]):
        c3 = ("PARTIAL", "Lean refinement of a concrete event machine; the runtime is linked by trace checking, "
              "not by proof")
    else:
        rc = axes.get("runtime_correspondence")
        c3 = ({"REFUTED": "REFUTED", "ASSUMED": "ASSUMED"}.get(rc, "OPEN"),
              "scope axis runtime_correspondence = {}".format(rc))
    eb = axes.get("environment_boundary")
    c4 = ({"REFUTED": "REFUTED", "ASSUMED": "ASSUMED"}.get(eb, "OPEN"), "scope axis environment_boundary = {}".format(eb))
    c5 = ("OPEN", "no independent human statement review recorded")
    c6 = (("RECORDED", "preregistered evidence: " + ", ".join(sorted({s[0] for s in pre_pass}))) if pre_pass else
          ("OPEN", "no preregistered evidence run"))
    names = ["a realistic honest task works under the declared mediation",
             "independently checked negative tests cover the bad actions and their bypasses",
             "the trusted kernel/model and the runtime transition boundary are linked by a justified refinement",
             "consequential side observations and failure channels are accounted for or bounded",
             "independent reviewers sign off on statement fidelity and assumptions",
             "experimental evidence is fresh, reproducible and preregistered"]
    return [(n, s, b) for n, (s, b) in zip(names, (c1, c2, c3, c4, c5, c6))]


def render_tests(m):
    sid = m["id"]
    d = SCEN / sid
    L = ["# {} tests".format(sid), "", GEN_MARKER, "",
         "Commands are listed only for files that exist. Run them from the repository root. Nothing here is run "
         "automatically.", ""]
    L += ["## Static checks", ""]
    if (d / "claim.lean").exists():
        L.append("- Claim file: `lake env lean scenarios/{}/claim.lean`".format(sid))
    L.append("- Scenario bundle (manifest schema, hashes): `python3 tools/check_scenarios.py`")
    mods = sorted({t["path"] for t in m["theorems"] if (ROOT / t["path"]).exists()})
    for p in mods:
        L.append("- Lean module: `lake build {}`".format(p[:-5].replace("/", ".")))
    tdirs = sorted({f.parent for f in d.rglob("test_*.py") if "evidence" not in f.parts})
    runners = sorted(f for f in d.rglob("run_*.py") if "evidence" not in f.parts)
    if tdirs or runners:
        L += ["", "## Harness", ""]
        for t in tdirs:
            L.append("- Unit tests: `python3 -m unittest discover -s {} -p 'test_*.py'`".format(t.relative_to(ROOT)))
        for r in runners:
            src = r.read_text(errors="replace")
            if "sudo" in src or "geteuid() != 0" in src or "root required" in src:
                priv = "needs root for its separate UIDs or cgroups"
            elif "refuse" in src.lower() and "root" in src.lower():
                priv = "runs unprivileged and refuses to run as root"
            else:
                priv = "see its docstring for privileges"
            L.append("- Runner: `{}` ({}; evidence runs need the frozen prereg)".format(r.relative_to(ROOT), priv))
    checks = sorted((ROOT / "tools").glob("check_{}_case.py".format(sid.lower().replace("-", ""))))
    ev = [e for e in m["evidence"] if (ROOT / e["path"]).exists()]
    if checks or ev:
        L += ["", "## Evidence", ""]
        for c in checks:
            L.append("- Independent recheck: `python3 {}`".format(c.relative_to(ROOT)))
        for e in ev:
            L.append("- Recorded: `{}` ({})".format(e["path"], e.get("outcome", "?")))
    L.append("")
    return "\n".join(L)


def render_threat(m):
    files = sorted({t["path"] for t in m["theorems"]})
    L = ["# {}: {}".format(m["id"], m["title"]), "", GEN_MARKER, "", "_Generated from manifest.json._", "",
         "**Bad event:** " + m["bad_event"], "", "**Adversary:** " + m["adversary"], "",
         "**Scope:** " + m["scope"], "", "**Refutation (what would show the claim wrong):** " + m["refutation"], "",
         "**Families:** " + ", ".join(m.get("families", [])), "", "**Model files:**", ""]
    L += ["- `{}`".format(f) for f in files] or ["- none"]
    L.append("")
    return "\n".join(L)


# ---------------------------------------------------------------- driver

def plan():
    manifests = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(SCEN.glob("SC-*/manifest.json"))]
    refs = path_refs(manifests)
    out = {}
    for m in manifests:
        d = SCEN / m["id"]
        rp = d / "result.md"
        cur = rp.read_text(encoding="utf-8") if rp.exists() else ""
        nm = NOTES_RE.search(cur)
        out[rp] = render_result(m, refs, nm.group(0) if nm else None)
        out[d / "tests" / "README.md"] = render_tests(m)
        th = d / "threat.md"
        if th.exists():
            text = th.read_text(encoding="utf-8")
            first = text.splitlines()[0] if text else ""
            if "catalog draft" in first or GEN_MARKER in text:
                out[th] = render_threat(m)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    drift, written, skipped = [], [], []
    for path, text in plan().items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur is not None and HAND_MARKER in cur:
            skipped.append(path)
            continue
        if cur != text:
            if a.check:
                drift.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                written.append(path)
    rel = lambda ps: [str(p.relative_to(ROOT)) for p in ps]
    if a.check:
        if drift:
            print("result-page drift (run python3 tools/build_results.py):\n  " + "\n  ".join(rel(drift)))
            return 1
        print("result pages consistent ({} hand-written skipped)".format(len(skipped)))
        return 0
    print("wrote {} file(s); {} hand-written skipped".format(len(written), len(skipped)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
