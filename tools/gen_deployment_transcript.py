#!/usr/bin/env python3
"""Generate ControlStack/Deployment/TranscriptReplay.lean from the archived Tier 2 clean-case broker transcript.
Every recorded request/response becomes one TrustedBroker.Step (denied responses are identity steps); the kernel then
checks the whole receipt chain with CheckedTrace.verified. --check regenerates and compares (CI)."""
import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
RUN=ROOT/'deployment/runs/tier2/containers-final'
OUT=ROOT/'ControlStack/Deployment/TranscriptReplay.lean'

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def archived():
    events=[e for e in json.loads((RUN/'events.json').read_text()) if e['case']=='clean']
    users={k:int(v['user']) for k,v in json.loads((RUN/'clean/compose.json').read_text())['services'].items()}
    return events,users

def generate(events=None,users=None,namespace='ControlStack.Deployment.TranscriptReplay'):
    if events is None:events,users=archived()
    assert len(events)==10 and all(e['case']=='clean' for e in events)
    ids={'digest':{},'lease':{},'nonce':{},'dest':{}}
    def ident(kind,key):
        table=ids[kind]
        if key not in table:table[key]=len(table)+1
        return table[key]
    L=[];defs=[];n=len(events)
    approvals={};leases={}
    # roles: numeric Compose users; separated is proved, not assumed
    for i,e in enumerate(events):
        q=e['request'];uid=users[e['service']];b=f's{i}';a=f's{i+1}';op=q['op']
        if not e['response']['ok']:
            if op=='effect_release':
                defs.append(f'def q{i} : TrustedBroker.Request := ⟨{uid}, {ident("nonce",q["nonce"])}, {ident("digest",q["digest"])}, {ident("dest",q["destination"])}, {ident("lease",q["lease_id"])}, 1⟩')
            defs.append(f'def {a} : TrustedBroker.State := {b}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.deny {b}')
            continue
        if op=='stage':
            assert hashlib.sha256(base64.b64decode(q['body_b64'])).hexdigest()==e['response']['result']
            d=ident('digest',e['response']['result'])
            defs.append(f'def {a} : TrustedBroker.State := {{ {b} with artifacts := TrustedBroker.put {b}.artifacts {d} true, intact := TrustedBroker.put {b}.intact {d} true }}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.stage {b} {uid} {d} (by ok) (by ok)')
        elif op=='review':
            d=ident('digest',q['digest'])
            defs.append(f'def {a} : TrustedBroker.State := {{ {b} with reviews := TrustedBroker.put {b}.reviews {d} (some {uid}) }}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.review {b} {uid} {d} (by ok) (by ok) (by ok)')
        elif op=='issue_lease':
            k=ident('lease',q['lease_id']);name=f'l{k}';leases[k]=name
            defs.append(f'def {name} : TrustedBroker.Lease := ⟨{q["agent_uid"]}, {q["budget"]}, 0, {q["expires"]}, false⟩\ndef {a} : TrustedBroker.State := {{ {b} with leases := TrustedBroker.put {b}.leases {k} (some {name}) }}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.issue {b} {uid} {k} {name} 0 '+' '.join(['(by ok)']*8))
        elif op=='approve':
            nonce=ident('nonce',q['nonce']);k=ident('lease',q['lease_id']);d=ident('digest',q['digest']);dest=ident('dest',q['destination']);name=f'a{nonce}';approvals[nonce]=name
            defs.append(f'def {name} : TrustedBroker.Approval := ⟨{d}, {dest}, {q["agent_uid"]}, {k}, {uid}, {q["expires"]}, false⟩\ndef {a} : TrustedBroker.State := {{ {b} with approvals := TrustedBroker.put {b}.approvals {nonce} (some {name}) }}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.approve {b} {uid} {nonce} {name} {leases[k]} 0 23703 '+' '.join(['(by ok)']*14))
        elif op=='effect_release':
            nonce=ident('nonce',q['nonce']);k=ident('lease',q['lease_id']);d=ident('digest',q['digest']);dest=ident('dest',q['destination']);name=f'q{i}'
            defs.append(f'def {name} : TrustedBroker.Request := ⟨{uid}, {nonce}, {d}, {dest}, {k}, 1⟩\ndef {a} : TrustedBroker.State := TrustedBroker.committed {b} {name} {approvals[nonce]} {leases[k]}\ntheorem tx{i} : TrustedBroker.Step R {b} {a} := TrustedBroker.Step.release {b} 0 {name} {approvals[nonce]} {leases[k]} ⟨'+', '.join(['(by ok)']*19+['⟨23703, rfl⟩','(by ok)'])+'⟩')
        else:raise ValueError(op)
    # Allowed has 21 conjuncts; the reviewer existential is the 20th, nonce freshness the 21st
    head=f'''import ControlStack.Deployment.R2Contracts
import ControlStack.Core.CheckedTrace

/-!
Checked replay of the recorded Tier 2 clean-case broker transcript (T4.4). GENERATED by tools/gen_deployment_transcript.py
from deployment/runs/tier2/containers-final/events.json (sha256 {sha(RUN/'events.json')}); do not edit.

What this establishes: the ten recorded requests/responses, read as `TrustedBroker.Step`s over complete model states
(a denied response is an identity step), form a chain accepted by `CheckedTrace.verified`, hence a `TrustedBroker.Trace`
from the initial state with cap 2, whose end state is Safe and Coherent with spent = releases = 2.
What it does NOT establish (and the omission examples below show it): that the transcript is complete (events the broker never reported are invisible; see the
omission examples), that the wall-clock `now` witness (0) is the broker's clock (it is only a feasible witness: no
timestamp was recorded), that the log is authentic, or any link from model releases to sink files (that is the receiver
refinement premise, checked on bytes by deployment/check_container_run.py).
-/
namespace {namespace}
open ControlStack

macro "ok" : tactic => `(tactic| first | rfl | exact Or.inl rfl | exact Or.inr rfl | decide)

def R : TrustedBroker.Roles :=
  {{ agent := fun u => u = 23701 ∨ u = 23702, reviewer := fun u => u = 23703, approver := fun u => u = 23704,
    admin := fun u => u = 23700, separated := by intro u h; rcases h with rfl | rfl <;> decide }}

def s0 : TrustedBroker.State := TrustedBroker.initial 2
'''
    tail=[]
    tail.append('def interpret : Nat → TrustedBroker.State\n'+''.join(f'  | {i} => s{i}\n' for i in range(n+1))+'  | _ => s0\n')
    tail.append('def replayStep (s op : Nat) : Nat :=\n'+''.join(f'  if s = {i} ∧ op = {i} then {i+1} else\n' for i in range(n))+'  s\n')
    tail.append('theorem table_checked (s op : Nat) : TrustedBroker.Step R (interpret s) (interpret (replayStep s op)) := by\n  unfold replayStep\n  split_ifs '+' '.join(f'with h{i}' if i==0 else f'h{i}' for i in range(n))+'\n'+''.join(f'  · rcases h{i} with ⟨rfl, rfl⟩; exact tx{i}\n' for i in range(n))+'  · exact .deny _\n')
    tail.append('def table : IndexedBrokerTable R := ⟨interpret, replayStep, table_checked⟩\n')
    tail.append('def receipts : List (CheckedTrace.Receipt Nat Nat) := ['+', '.join(f'⟨{i}, {i}, {i+1}⟩' for i in range(n))+']\n')
    tail.append('theorem transcript_checked : CheckedTrace.verified table.step 0 receipts = true := by decide\n')
    tail.append(f'''theorem recorded_end : CheckedTrace.recordedEnd 0 receipts = {n} := by decide

theorem runtime_trace : TrustedBroker.Trace R (TrustedBroker.initial 2) s{n} := by
  have h := indexed_receipts_sound R table receipts 0 transcript_checked
  rw [recorded_end] at h
  exact h

theorem final_safe : TrustedBroker.Safe s{n} :=
  TrustedBroker.trace_preserves R _ _ (TrustedBroker.initial_safe 2) runtime_trace

theorem final_coherent : TrustedBroker.Coherent s{n} :=
  TrustedBroker.trace_coherent R _ _ (TrustedBroker.initial_coherent 2) runtime_trace

/-- The recorded shared budget was spent exactly by the two approved releases. -/
theorem final_counts : s{n}.cap = 2 ∧ s{n}.spent = 2 ∧ s{n}.releases = 2 ∧ s{n}.consumed = [2, 1] ∧ s{n}.halted = false := by
  decide

/-- The replayed denial (the same nonce released twice) is a model denial: in the state after the first release the same
request is not Allowed, whichever approval and lease the caller names. -/
theorem replay_was_not_allowed (now : Nat) (a' : TrustedBroker.Approval) (l' : TrustedBroker.Lease) :
    ¬ TrustedBroker.Allowed R s8 now q8 a' l' :=
  TrustedBroker.committed_nonce_unusable R s7 q7 a1 l1 now q8 a' l' rfl

/-! Omission examples: what a verified transcript can and cannot tell you. -/

/-- Dropping a state-changing receipt from the middle breaks the chain: the checker rejects it. -/
def withoutMiddleRelease : List (CheckedTrace.Receipt Nat Nat) := receipts.eraseIdx 7
theorem omitted_state_change_is_rejected : CheckedTrace.verified table.step 0 withoutMiddleRelease = false := by decide

/-- Dropping the recorded tail leaves a valid shorter trace: truncation is accepted. Completeness is not checked. -/
def withoutLastRelease : List (CheckedTrace.Receipt Nat Nat) := receipts.take 9
theorem omitted_tail_is_accepted : CheckedTrace.verified table.step 0 withoutLastRelease = true := by decide
theorem omitted_tail_changes_the_end : CheckedTrace.recordedEnd 0 withoutLastRelease ≠ CheckedTrace.recordedEnd 0 receipts := by decide

/-- Dropping the denied replay's receipt breaks the chain of recorded state ids, so this checker rejects it. A producer that
renumbered a shorter log consistently would be accepted: the checker sees only the receipts it is given. -/
def withoutDenial : List (CheckedTrace.Receipt Nat Nat) := receipts.eraseIdx 8
theorem omitted_denial_breaks_the_id_chain : CheckedTrace.verified table.step 0 withoutDenial = false := by decide
''')
    return head+'\n'.join(defs)+'\n\n'+'\n'.join(tail)+f'\nend {namespace}\n'+''.join(f'#print axioms {namespace}.{name}\n' for name in ('runtime_trace','final_safe','final_coherent','final_counts','replay_was_not_allowed','omitted_state_change_is_rejected','omitted_tail_is_accepted','omitted_tail_changes_the_end','omitted_denial_breaks_the_id_chain'))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text:raise SystemExit('stale generated Lean: '+str(OUT)+' (run tools/gen_deployment_transcript.py)')
        print('transcript module consistent')
    else:OUT.write_text(text);print('wrote',OUT)
