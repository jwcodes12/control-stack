#!/usr/bin/env python3
"""Import a verified blind batch from ~/projects/blind-work/<tag> into docs/lean-english/one-to-one/blind-<tag>/ and rebuild BLIND-INDEX.md.

Refuses a batch whose VERIFY.json is missing or not `all_pass` with the typed hashes frozen before the originals were opened.
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OO = ROOT / "docs/lean-english/one-to-one"
VERDICTS = ("EQUIVALENT", "ENGLISH_STRONGER", "ENGLISH_WEAKER", "DIFFERENT", "NOT_FORMALISABLE", "UNDECIDED")


def import_batch(tag, work):
    w = Path(work).expanduser() / tag
    v = json.loads((w / "VERIFY.json").read_text())
    if not (v.get("all_pass") and v.get("frozen_before_open")):
        sys.exit(f"{tag}: VERIFY.json does not show all gates passing and freeze-before-open; not importing")
    src = w / "b/docs/lean-english/one-to-one" / f"blind-{tag}"
    dst = OO / f"blind-{tag}"
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("gate-tmp", "__pycache__"))
    pa = dst / "phase-a"
    pa.mkdir(exist_ok=True)
    shutil.copytree(w / "a/defs", pa / "defs")
    shutil.copytree(w / "a/input", pa / "input")
    shutil.copy(w / "a/PROMPT-A.md", pa / "PROMPT.md")
    shutil.copy(w / "a/PROMPT-B.md", dst / "PROMPT-phase-b.md")
    shutil.copy(w / "A-AUDIT.txt", pa / "AUDIT.txt")
    shutil.copy(w / "B-last.txt", dst / "FINAL-MESSAGE.md")
    shutil.copy(w / "VERIFY.json", dst / "VERIFY.json")
    for tagname, ev, out in (("A", "A-events.jsonl", pa / "COMMANDS.txt"), ("B", "B-events.jsonl", dst / "COMMANDS-phase-b.txt")):
        cmds = []
        for line in (w / ev).read_text().splitlines():
            try:
                e = json.loads(line)
            except ValueError:
                continue
            it = e.get("item", {})
            if it.get("type") == "command_execution" and e.get("type") == "item.started":
                cmds.append(it["command"])
        out.write_text("\n\n---\n".join(cmds) + "\n")
    (pa / "README.md").write_text(f"# Phase A, batch {tag}\n\nPrepared by `tools/blind_one_to_one.py`, run by `tools/blind_batch_runner.py`. Sol saw only `input/batch.md` and `defs/` (definition-only excerpts, claims redacted, "
                                  "no originals, objects or toolchain). `COMMANDS.txt` is every command; `AUDIT.txt` the transcript audit; hashes in `../back/BACK-HASHES.json`. "
                                  "Verification (independent re-gate, freeze-before-open ordering): `../VERIFY.json`.\n")
    print("imported", tag)


def index():
    rows, total = [], {}
    for d in sorted(OO.glob("blind-*")):
        claims = d / "CLAIMS.txt"
        msg = d / "FINAL-MESSAGE.md"
        if not (claims.exists() and msg.exists()):
            continue
        names = {int(l.split("\t")[0]): l.split("\t")[1] for l in claims.read_text().strip().splitlines()}
        verdicts = {}
        for line in msg.read_text().splitlines():
            m = re.match(r"\|\s*(\d+)\b[^|]*\|\s*\**([A-Z_]+)\**\s*\|", line)
            if m and m.group(2) in VERDICTS:
                verdicts[int(m.group(1))] = m.group(2)
        ver = d / "VERIFY.json"
        ok = json.loads(ver.read_text()).get("all_pass") if ver.exists() else None
        for n, name in sorted(names.items()):
            v = verdicts.get(n, "?")
            total[v] = total.get(v, 0) + 1
            rows.append((d.name, n, name, v, ok))
    lines = ["# Blind one-to-one results, all batches", "",
             "Generated by `tools/import_blind_batch.py`. A row is a blind (phase A hashed before any original was opened), gate-checked verdict; `re-gated` says the orchestrator re-ran the batch's gates and they passed "
             "(`n/a` for the first two batches, which were verified by hand and are described in `blind-v1/SUMMARY.md`). Model-written, model-checked, no independent human review.", "",
             "Totals: " + ", ".join(f"{k}: {v}" for k, v in sorted(total.items())), "", "| Batch | # | Claim | Verdict | re-gated |", "|---|---|---|---|---|"]
    for b, n, name, v, ok in rows:
        lines.append(f"| {b} | {n} | `{name}` | {v} | {'yes' if ok else ('n/a' if ok is None else 'NO')} |")
    (OO / "BLIND-INDEX.md").write_text("\n".join(lines) + "\n")
    print("index:", total)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", nargs="*", default=[])
    ap.add_argument("--work", default="~/projects/blind-work")
    a = ap.parse_args()
    for t in a.tag:
        import_batch(t, a.work)
    index()
