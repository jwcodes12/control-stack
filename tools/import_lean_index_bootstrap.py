#!/usr/bin/env python3
"""Import complete GitHub Actions Lean-index bootstrap log chunks.

This only copies generated bytes out of an approved Actions job; it is NOT
proof certification, a runtime assurance result, or an English-fidelity check.
Model-written and model-reviewed. No independent human review.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "lean-english"
CHUNK = re.compile(r"(CSDEPCHUNK|CSTRACECHUNK):(\d{8}):([^\r\n]*)")
OUTPUTS = {
    "CSDEPCHUNK": ("DEPENDENCIES.json", "DEPENDENCIES.md"),
    "CSTRACECHUNK": ("TRACEABILITY.json", "TRACEABILITY.md"),
}
ALLOWED = {"propext", "Quot.sound", "Classical.choice"}


def reconstruct(raw: str, label: str) -> dict[str, str]:
    chunks = {}
    for line in raw.splitlines():
        match = CHUNK.search(line)
        if not match or match.group(1) != label:
            continue
        offset = int(match.group(2))
        if offset in chunks:
            raise ValueError(f"duplicate {label} offset {offset}")
        chunks[offset] = match.group(3)
    if not chunks or min(chunks) != 0:
        raise ValueError(f"missing first {label} chunk")
    text = ""
    for offset, chunk in sorted(chunks.items()):
        if offset != len(text):
            raise ValueError(f"missing/truncated {label} chunk at {len(text)}")
        text += chunk
    obj = json.loads(text)
    if not isinstance(obj, dict) or set(obj) != {"json", "md"}:
        raise ValueError(f"invalid {label} bootstrap envelope")
    if any(not isinstance(v, str) for v in obj.values()):
        raise ValueError(f"invalid {label} bootstrap file text")
    return obj


def check_payload(dep: dict, trace: dict) -> None:
    deps = json.loads(dep["json"])
    claims = json.loads(trace["json"])
    for name, obj in (("dependencies", deps), ("traceability", claims)):
        if obj.get("claim_count") != 187 or len(obj.get("claims", [])) != 187:
            raise ValueError(f"{name}: not exactly 187 claims")
        if [r.get("ordinal") for r in obj["claims"]] != list(range(1, 188)):
            raise ValueError(f"{name}: missing, repeated or reordered claim IDs")
    if claims.get("independent_human_review") is not False:
        raise ValueError("unexpected independent-review assertion")
    for d, c in zip(deps["claims"], claims["claims"]):
        if d.get("lean") != c.get("lean"):
            raise ValueError("dependency/traceability declaration identity mismatch")
        if d.get("axioms_standard") is not True or set(d.get("axioms", [])) - ALLOWED:
            raise ValueError("nonstandard axiom footprint")
        if c.get("verified") is not False:
            raise ValueError("unexpected English verification assertion")
        if c.get("dependency_row") != d:
            raise ValueError("traceability did not use same environment dependency row")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("log", type=Path, help="full GitHub Actions kernel job log")
    p.add_argument("--force", action="store_true", help="allow replacing older artifacts")
    args = p.parse_args()
    raw = args.log.read_text()
    dep = reconstruct(raw, "CSDEPCHUNK")
    trace = reconstruct(raw, "CSTRACECHUNK")
    check_payload(dep, trace)
    output = {
        OUT / OUTPUTS[label][i]: obj["json" if i == 0 else "md"]
        for label, obj in (("CSDEPCHUNK", dep), ("CSTRACECHUNK", trace))
        for i in range(2)
    }
    if not args.force:
        for path, data in output.items():
            if path.exists() and path.read_text() != data:
                raise ValueError(f"refusing to overwrite nonmatching artifact: {path}")
    for path, data in output.items():
        path.write_text(data)
        print(f"imported {path.relative_to(ROOT)} ({len(data)} characters)")
    print("Imported from CI logs only; Lean/claim verification still requires --check on committed files.")


if __name__ == "__main__":
    main()
